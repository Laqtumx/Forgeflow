"""Approval and publishing.

The contract with the human is: *you approve a hash, and only that hash can be
published.*

Flow:

1. ``approve`` records the fingerprint the human typed, after checking it
   against a stored, verified attempt. A fingerprint that matches nothing is
   rejected, and a fingerprint for an attempt that did not pass verification is
   rejected too.
2. ``publish`` re-derives the patch from the base commit in a fresh clone,
   re-applies the same edits, and recomputes the hash. If it differs from the
   approved value, publishing aborts *before* any network write.
3. The branch is pushed to the user's fork with the publish token, and a draft
   PR is opened against the upstream repository, disclosing AI assistance.
4. The PR is always a draft. ForgeFlow never merges, and never marks a PR ready
   for review.
"""

from __future__ import annotations

import re
import shutil
from dataclasses import dataclass
from pathlib import Path

from . import gitops
from .config import Config
from .errors import ForgeFlowError, PublishError
from .github_client import GitHubClient
from .models import RepoRef
from .store import Store

SHA256_RE = re.compile(r"^[0-9a-f]{64}$")

AI_DISCLOSURE = (
    "This pull request was generated by an AI agent (ForgeFlow) on behalf of "
    "@{author}. It is a draft for review, not a merge request."
)

PR_BODY_TEMPLATE = """\
## What this changes

{summary}

## Why

Fixes #{issue_number}

**Root-cause hypothesis (AI-generated):**

{hypothesis}

## How it was checked

- The repository's own test suite was run in a Docker sandbox (non-root,
  network disabled during tests) **before** and **after** the patch.
- Baseline test summary: `{baseline_summary}`
- Patched test summary: `{patched_summary}`
- Pre-existing failures were compared and excluded, so this patch is not
  credited with them.
- Lint: {lint_summary}
- The changed files were limited to: {files}

## Review notes

- This is a **draft**. It has not been merged and will not be merged by the tool.
- The patch is derived only from exact search/replace edits proposed by the
  model. The model had no shell access and could not run anything.
- Issue text and repository contents are treated as untrusted input.
- Patch fingerprint (SHA-256): `{fingerprint}`

---

{disclosure}
"""


@dataclass
class Approval:
    approval_id: int
    attempt_id: int
    fingerprint: str
    approved_by: str


@dataclass
class PublishResult:
    branch: str
    pr_url: str | None
    pr_number: int | None
    fingerprint: str
    fork_owner: str


def _normalise_fingerprint(value: str) -> str:
    return value.strip().lower().removeprefix("sha256:").strip()


def approve(
    store: Store,
    fingerprint: str,
    *,
    approved_by: str,
) -> Approval:
    """Record a human approval for one verified attempt.

    Refuses anything that is not a verified, passing attempt: the approval path
    must not be a way to publish an unverified patch.
    """
    normalised = _normalise_fingerprint(fingerprint)
    if not SHA256_RE.match(normalised):
        raise PublishError(
            f"{fingerprint!r} is not a SHA-256 fingerprint (expected 64 hex characters)"
        )

    attempt = store.find_attempt_by_fingerprint(normalised)
    if attempt is None:
        raise PublishError(
            "no verified attempt matches that fingerprint. Run `forgeflow run` "
            "first, or copy the fingerprint printed for the accepted attempt."
        )
    if not attempt["passed"]:
        raise PublishError(
            f"attempt {attempt['attempt']} with that fingerprint did not pass "
            "verification, so it cannot be approved."
        )

    approval_id = store.record_approval(int(attempt["id"]), normalised, approved_by)
    return Approval(
        approval_id=approval_id,
        attempt_id=int(attempt["id"]),
        fingerprint=normalised,
        approved_by=approved_by,
    )


def publish(
    config: Config,
    store: Store,
    approval_id: int,
    *,
    github: GitHubClient | None = None,
    dry_run: bool = False,
) -> PublishResult:
    """Rebuild, verify the fingerprint, push to the fork, open a draft PR."""
    row = store._conn.execute(
        "SELECT * FROM approvals WHERE id=?", (approval_id,)
    ).fetchone()
    if row is None:
        raise PublishError(f"approval {approval_id} not found")
    approval = dict(row)

    attempt = store.get_attempt(int(approval["attempt_id"]))
    if attempt is None:
        raise PublishError("the approved attempt has disappeared from the store")

    run = store.get_run_by_attempt(int(approval["attempt_id"]))
    if run is None:
        raise PublishError("the run that produced this attempt is missing")

    repo = RepoRef.parse(str(run["repo"]))
    issue_number = run["issue_number"]
    base_commit = run["base_commit"]
    if not base_commit:
        raise PublishError("the run has no recorded base commit; cannot rebuild the patch")

    # Rebuild the plan from what was stored, not from anything in memory.
    from .models import EditPlan as _EditPlan

    plan = _EditPlan.model_validate({"edits": _json_load(attempt["edits_json"])})
    expected = str(approval["fingerprint"])

    config.require_publish_credentials()
    assert config.github_publish_token and config.fork_owner

    github = github or GitHubClient(config.github_read_token, config.github_publish_token)

    if dry_run:
        rebuilt = gitops.rebuild_patch(
            repo,
            base_commit,
            plan,
            expected,
            config.work_dir / f"dryrun-{approval_id}",
            token=config.github_read_token,
            depth=config.clone_depth,
        )
        _cleanup(rebuilt.checkout)
        return PublishResult(
            branch=_branch_name(issue_number, expected),
            pr_url=None,
            pr_number=None,
            fingerprint=rebuilt.fingerprint,
            fork_owner=config.fork_owner,
        )

    # --- 1. rebuild and verify the hash BEFORE any write -------------------
    rebuilt = gitops.rebuild_patch(
        repo,
        base_commit,
        plan,
        expected,
        config.work_dir / f"publish-{approval_id}",
        token=config.github_read_token,
        depth=config.clone_depth,
    )
    checkout = rebuilt.checkout

    branch = _branch_name(issue_number, rebuilt.fingerprint)
    message = _commit_message(run, attempt, rebuilt.fingerprint)

    # --- 2. commit on a branch and push to the fork -----------------------
    try:
        gitops.prepare_branch(checkout, base_commit, branch, message)
        github.ensure_fork(repo, config.fork_owner)
        github.wait_for_fork_ready(repo, config.fork_owner)
        gitops.push_branch(
            checkout,
            repo.name,
            config.fork_owner,
            branch,
            config.github_publish_token,
        )
    except ForgeFlowError as exc:
        store.update_approval(approval_id, "failed", branch=branch, error_message=str(exc))
        _cleanup(checkout)
        raise

    # --- 3. open the draft PR against upstream ---------------------------
    body = _pr_body(run, attempt, rebuilt, config, issue_number)
    title = _pr_title(run, issue_number)
    try:
        payload = github.open_draft_pull_request(
            repo,
            title=title,
            body=body,
            head=f"{config.fork_owner}:{branch}",
            base=str(run["default_branch"] or "main"),
        )
    except ForgeFlowError as exc:
        store.update_approval(
            approval_id, "pushed-no-pr", branch=branch, error_message=str(exc)
        )
        _cleanup(checkout)
        raise PublishError(
            f"the branch was pushed to your fork but the draft PR could not be "
            f"opened: {exc}. Open it manually from {config.fork_owner}:{branch}."
        ) from exc

    pr_url = str(payload.get("html_url") or "")
    pr_number = payload.get("number")
    store.update_approval(approval_id, "published", branch=branch, pr_url=pr_url)
    _cleanup(checkout)
    return PublishResult(
        branch=branch,
        pr_url=pr_url,
        pr_number=int(pr_number) if pr_number is not None else None,
        fingerprint=rebuilt.fingerprint,
        fork_owner=config.fork_owner,
    )


def _cleanup(checkout: Path) -> None:
    """Remove a publish working tree once it is no longer needed."""
    shutil.rmtree(checkout.parent, ignore_errors=True)


def _json_load(text: str | None) -> list:
    import json

    if not text:
        return []
    try:
        value = json.loads(text)
    except ValueError as exc:
        raise PublishError(f"stored edits are not valid JSON: {exc}") from exc
    if not isinstance(value, list):
        raise PublishError("stored edits are not a list")
    return value


def _branch_name(issue_number: int | None, fingerprint: str) -> str:
    suffix = fingerprint[:8] if fingerprint else "unknown"
    if issue_number:
        return f"forgeflow/issue-{issue_number}-{suffix}"
    return f"forgeflow/patch-{suffix}"


def _commit_message(run: dict, attempt: dict, fingerprint: str) -> str:
    subject = f"ForgeFlow: candidate fix for #{run['issue_number']}"
    return (
        f"{subject}\n\n"
        f"Patch fingerprint (SHA-256): {fingerprint}\n"
        f"Attempt: {attempt['attempt']}\n"
        f"Files changed: {attempt['files_changed']}\n\n"
        "Generated by an AI agent (ForgeFlow) on behalf of a human reviewer.\n"
        "Not merged, not reviewed by a maintainer. See the draft pull request.\n"
    )


def _pr_title(run: dict, issue_number: int | None) -> str:
    title = str(run.get("issue_title") or "").strip()
    if title:
        return f"[ForgeFlow] {title[:120]}"
    return f"[ForgeFlow] candidate fix for #{issue_number}"


def _pr_body(
    run: dict,
    attempt: dict,
    rebuilt: gitops.RebuiltPatch,
    config: Config,
    issue_number: int | None,
) -> str:
    import json

    summary = str(run.get("analysis_summary") or "See the analysis recorded in ForgeFlow.")
    hypothesis = str(run.get("analysis_hypothesis") or "(not recorded)")
    files = ", ".join(json.loads(attempt["files_changed"] or "[]")) or "(none)"
    author = config.fork_owner or "the submitter"

    return PR_BODY_TEMPLATE.format(
        summary=summary,
        issue_number=issue_number,
        hypothesis=hypothesis,
        baseline_summary=str(run.get("baseline_summary") or "recorded in ForgeFlow"),
        patched_summary=str(run.get("patched_summary") or "recorded in ForgeFlow"),
        lint_summary=str(run.get("lint_summary") or "recorded in ForgeFlow"),
        files=files,
        fingerprint=rebuilt.fingerprint,
        disclosure=AI_DISCLOSURE.format(author=author),
    )


def publish_pending(config: Config, store: Store) -> list[dict]:
    """Report approvals that were recorded but never completed."""
    rows = store._conn.execute(
        "SELECT id, fingerprint, publish_state, branch, pr_url, error_message"
        " FROM approvals WHERE publish_state != 'published' ORDER BY id"
    ).fetchall()
    return [dict(row) for row in rows]
